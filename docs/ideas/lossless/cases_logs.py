"""Repetition, log, listing and diff ideas: #19 #20 #22 #23 #24 #27 #28 #29 #30 #392 #410 #423 #516 #782 #799 #888 #976 #1078 #1079.

Reference prototypes, fixtures and oracles; see harness.py for the rules. Three conventions used throughout:

* In-band signals are made unambiguous one of two ways. Headerless forms ("line [x5]", a repeat marker) escape any original
  line that looks like the marker, so decode is a bijection. Forms with a legend line (starts with the sigil "§") refuse
  when the input could be misread (return it unchanged) and escape only an input that itself starts with the sigil
  (RAW prefix). Both escapes may grow an adversarial input, which is why roundtrip cases set idempotent=False: an
  injective encoding cannot also be idempotent (see #100 in cases_00_examples.py).
* The diff ideas (#30 #782 #1078 #1079) share one oracle, `parse_diff`: a small state machine that reads a git diff (plain or in
  any of the four compact forms) into (file, hunk, added/removed/context line) events. Git diffs are normally kept verbatim by
  the hook because Edit needs exact text, so these forms are for display-only diffs and each case carries negatives.
* Fixtures are generated by small functions from a seeded RNG so they are deterministic and realistic in shape.
"""
