# #29 Strip git boilerplate. Equivalent: dropped are (use "git ...") advice lines, hint: lines of commands that did not
# fail, remote: progress/blank lines. Runs of per-file CRLF warnings become ONE line that keeps every file name.
# Narrower than the idea text: 'remote:' lines that carry content (PR URLs, hook messages, errors) are kept, and hint:
# lines are kept when the output shows an error or a rejected ref, because there they explain the failure.

_USE = re.compile(r'[ \t]+\(use "git [^\n]*\)')
_REMOTE_NOISE = re.compile(r"remote:(?: (?:Enumerating|Counting|Compressing) objects:| Resolving deltas:| Total ).*|remote:\s*")
_CRLF_W = re.compile(r"warning: in the working copy of '([^'\s]+)', (LF|CRLF) will be replaced by (CRLF|LF) the next time Git touches it")


def _failed(lines: list[str]) -> bool:
    return any(l.startswith(("error:", "fatal:", "CONFLICT")) or "[rejected]" in l or "[remote rejected]" in l for l in lines)


def git_strip(text: str) -> str:
    lines = text.split("\n")
    failing = _failed(lines)
    out: list[str] = []
    i = 0
    while i < len(lines):
        l = lines[i]
        if _USE.fullmatch(l) or _REMOTE_NOISE.fullmatch(l) or (l.startswith("hint:") and not failing):
            i += 1
            continue
        m = _CRLF_W.fullmatch(l)
        if m and m.group(2) != m.group(3):
            names, j = [], i
            while j < len(lines):
                mj = _CRLF_W.fullmatch(lines[j])
                if not (mj and (mj.group(2), mj.group(3)) == (m.group(2), m.group(3))):
                    break
                names.append(mj.group(1))
                j += 1
            if len(names) >= 2:
                out.append(f"warning: {m.group(2)} will be replaced by {m.group(3)} the next time Git touches it (working copy of: " + " ".join(f"'{n}'" for n in names) + ")")
                i = j
                continue
        out.append(l)
        i += 1
    enc = "\n".join(out)
    return enc if len(enc) < len(text) else text


_DIRS = {"LF will be replaced by CRLF the next time Git touches it": "LF>CRLF", "CRLF will be replaced by LF the next time Git touches it": "CRLF>LF"}


def _git_events(text: str) -> list[tuple]:
    """Oracle view, written with string methods instead of the encoder's regexes: the lines that matter, in order, with each
    CRLF warning (alone or inside a fold line) turned into a ('W', direction, file) event."""
    lines = text.split("\n")
    failing = any(l.startswith(("error:", "fatal:", "CONFLICT")) or "[rejected]" in l or "[remote rejected]" in l for l in lines)
    ev: list[tuple] = []
    for l in lines:
        s = l.lstrip(" \t")
        if s != l and s.startswith('(use "git ') and l.endswith(")"):
            continue
        if l.startswith("remote:") and (l[7:].strip() == "" or l.startswith(("remote: Enumerating objects:", "remote: Counting objects:", "remote: Compressing objects:", "remote: Resolving deltas:", "remote: Total "))):
            continue
        if l.startswith("hint:") and not failing:
            continue
        pre = "warning: in the working copy of '"
        if l.startswith(pre) and "', " in l:
            name, _, rest = l[len(pre):].partition("', ")
            if name and not any(c.isspace() or c == "'" for c in name) and rest in _DIRS:
                ev.append(("W", _DIRS[rest], name))
                continue
        head, sep, names = l.partition(" the next time Git touches it (working copy of: ")
        if sep and head.startswith("warning: ") and names.startswith("'") and names.endswith("')"):
            d = head[len("warning: "):] + " the next time Git touches it"
            if d in _DIRS:
                ev += [("W", _DIRS[d], n) for n in names[1:-2].split("' '")]
                continue
        ev.append(("L", l))
    return ev


def git_equivalent(x: str, e: str) -> bool:
    return _git_events(x) == _git_events(e)


