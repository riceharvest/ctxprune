# #392 git blame: one header per run of lines from the same commit, then 'lineno TAB code'. Roundtrip. The time of day
# and timezone are KEPT (the idea's measured variant omitted them, which is lossy). All lines must parse as default-format
# blame and the line-number padding must be the one git derives from the widest number, else the input is left alone.

_BLAME = re.compile(r"(?P<head>\^?[0-9a-f]{7,40} (?:\S+ )?\(.*? [0-9]{4}-[0-9]{2}-[0-9]{2} [0-9]{2}:[0-9]{2}:[0-9]{2} [+-][0-9]{4}) (?P<gap> *)(?P<n>[0-9]+)\) (?P<code>.*)")
BLAME_MAGIC = "§blame (a header line per commit run; rows are 'lineno<TAB>code')\n"


def blame_core(text: str):
    lines, nl = split_nl(text)
    ms = [_BLAME.fullmatch(l) for l in lines]
    if not lines or not all(ms):
        return None
    w = max(len(m.group("n")) for m in ms)
    if any(len(m.group("gap")) != w - len(m.group("n")) for m in ms):
        return None
    out, prev = [], None
    for m in ms:
        if m.group("head") != prev:
            out.append(m.group("head"))
            prev = m.group("head")
        out.append(f"{m.group('n')}\t{m.group('code')}")
    return join_nl(out, nl)


def blame_decode(body: str) -> str:
    lines, nl = split_nl(body)
    rows = [re.fullmatch(r"([0-9]+)\t(.*)", l, re.S) for l in lines]
    w = max((len(r.group(1)) for r in rows if r), default=0)
    out, head = [], ""
    for l, r in zip(lines, rows):
        if r:
            out.append(f"{head} {' ' * (w - len(r.group(1)))}{r.group(1)}) {r.group(2)}")
        else:
            head = l
    return join_nl(out, nl)


blame_encode, blame_unencode = framed(BLAME_MAGIC, blame_core, blame_decode)


