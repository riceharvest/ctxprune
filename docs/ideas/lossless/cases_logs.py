# #23 Timestamp factoring: the date shared by a log's lines moves to a header; each line keeps hh:mm:ss[.fff][Z].
# Roundtrip. Lines of another date stay whole. Escape: an original line that starts like a bare time gets a backslash.

_TS_HEAD = re.compile(r"([0-9]{4}-[0-9]{2}-[0-9]{2})([T ])(?=[0-9]{2}:[0-9]{2}:[0-9]{2})")
_BARE_TIME = re.compile(r"\\*[0-9]{2}:[0-9]{2}:[0-9]{2}")
TS_MAGIC = "§ts "


def ts_core(text: str):
    lines = text.split("\n")
    votes: Counter = Counter()
    for l in lines:
        m = _TS_HEAD.match(l)
        if m:
            votes[(m.group(1), m.group(2))] += 1
    if not votes:
        return None
    (date, sep), n = votes.most_common(1)[0]
    if n < 3:
        return None
    pre = date + sep
    out = []
    for l in lines:
        if l.startswith(pre) and re.match(r"[0-9]{2}:[0-9]{2}:[0-9]{2}", l[len(pre):]):
            out.append(l[len(pre):])
        elif _BARE_TIME.match(l):
            out.append("\\" + l)
        else:
            out.append(l)
    return f"date={date} sep={'T' if sep == 'T' else 'space'} (hh:mm:ss-led lines carry this date)\n" + "\n".join(out)


def ts_decode(body: str) -> str:
    head, _, rest = body.partition("\n")
    m = re.match(r"date=([0-9-]{10}) sep=(T|space)", head)
    pre = m.group(1) + ("T" if m.group(2) == "T" else " ")
    out = []
    for l in rest.split("\n"):
        if _BARE_TIME.match(l):
            out.append(l[1:] if l.startswith("\\") else pre + l)
        else:
            out.append(l)
    return "\n".join(out)


ts_encode, ts_unencode = framed(TS_MAGIC, ts_core, ts_decode)


