# #22 Periodic multi-line blocks: a k-line stanza (k>=2) repeated back to back is written once plus a marker line.
# Roundtrip. Escape: an original line shaped like the marker (with any number of leading backslashes) gets one more.

_PMARK = re.compile(r"(\\*)\[the ([0-9]+) lines above: x([0-9]+) total\]")


def _pesc(l: str) -> str:
    return "\\" + l if _PMARK.fullmatch(l) else l


def period_encode(text: str, kmax: int = 12) -> str:
    lines = text.split("\n")
    ambiguous = any(_PMARK.fullmatch(l) for l in lines)
    out: list[str] = []
    i, n = 0, len(lines)
    while i < n:
        best = None
        for k in range(2, min(kmax, (n - i) // 2) + 1):
            stanza = lines[i : i + k]
            reps = 1
            while lines[i + reps * k : i + (reps + 1) * k] == stanza:
                reps += 1
            if reps >= 2:
                marker = f"[the {k} lines above: x{reps} total]"
                saved = (reps - 1) * sum(len(l) + 1 for l in stanza) - (len(marker) + 1)
                if saved > 0 and (best is None or saved > best[0]):
                    best = (saved, k, reps, marker)
        if best:
            _, k, reps, marker = best
            out += [_pesc(l) for l in lines[i : i + k]] + [marker]
            i += k * reps
        else:
            out.append(_pesc(lines[i]))
            i += 1
    enc = "\n".join(out)
    return enc if (ambiguous or len(enc) < len(text)) else text


def period_decode(text: str) -> str:
    out: list[str] = []
    for line in text.split("\n"):
        m = _PMARK.fullmatch(line)
        if m and not m.group(1):
            k, reps = int(m.group(2)), int(m.group(3))
            out += out[-k:] * (reps - 1)
        elif m:
            out.append(line[1:])
        else:
            out.append(line)
    return "\n".join(out)


