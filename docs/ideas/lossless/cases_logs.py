# #27 Tree-ify file listings (find, rg --files): one path per line becomes 'indent + new components'. Roundtrip.
# Order-preserving front coding: the indent is the number of leading '/'-components shared with the previous path, so
# a sorted find listing prints each directory once and an unsorted rg --files listing still decodes exactly.
# Only 'clean' lists are rewritten: every component non-empty and not starting with whitespace (else the indent is ambiguous).

TREE_MAGIC = "§tree (n leading spaces = keep the first n '/'-parts of the line above)\n"


def _clean_path(p: str) -> bool:
    comps = p.split("/")
    if p.startswith("/"):
        comps = comps[1:]
    return bool(comps) and all(c and not c[0].isspace() for c in comps)


def tree_core(text: str):
    lines, nl = split_nl(text)
    if not lines or not all(_clean_path(l) for l in lines):
        return None
    out, prev = [], []
    for l in lines:
        comps = l.split("/")
        c = 0
        while c < min(len(prev), len(comps) - 1) and prev[c] == comps[c]:
            c += 1
        out.append(" " * c + "/".join(comps[c:]))
        prev = comps
    return join_nl(out, nl)


def tree_decode(body: str) -> str:
    lines, nl = split_nl(body)
    out, prev = [], []
    for l in lines:
        c = len(l) - len(l.lstrip(" "))
        prev = prev[:c] + l[c:].split("/")
        out.append("/".join(prev))
    return join_nl(out, nl)


tree_encode, tree_unencode = framed(TREE_MAGIC, tree_core, tree_decode)


