SIG = "§"
RAW = "§raw\n"


def split_nl(text: str) -> tuple[list[str], bool]:
    """'a\\nb\\n' -> (['a','b'], True); 'a\\nb' -> (['a','b'], False); '' -> ([], False)."""
    if text.endswith("\n"):
        return text[:-1].split("\n"), True
    return (text.split("\n") if text else []), False


def join_nl(lines: list[str], nl: bool) -> str:
    return "\n".join(lines) + ("\n" if nl else "")


def framed(magic: str, core_enc, core_dec=None):
    """Wrap a core transform that returns a body (or None when not applicable or ambiguous) behind a legend line `magic`.
    Not applicable / not shorter -> the input unchanged; an input that itself starts with the sigil is escaped with RAW."""

    def enc(text: str) -> str:
        body = core_enc(text)
        if body is not None:
            out = magic + body
            if len(out) < len(text):
                return out
        return RAW + text if text.startswith(SIG) else text

    def dec(t: str) -> str:
        if t.startswith(RAW):
            return t[len(RAW):]
        if t.startswith(magic):
            return core_dec(t[len(magic):])
        return t

    return enc, dec


