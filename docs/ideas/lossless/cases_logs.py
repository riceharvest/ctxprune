# #28 Group grep -rn / rg -n --no-heading hits by file: a run of 3+ 'file:LINE:text' lines in one file becomes
# '§N file' plus N rows 'LINE:text'. Roundtrip. Context lines (file-12-text, '--') are left verbatim and end a run.

_HIT = re.compile(r"([^:\n]+):([0-9]+):(.*)")
GREP_MAGIC = "§grep (§N file: the next N lines are 'line:text' hits in that file)\n"


def grep_core(text: str):
    lines = text.split("\n")
    files = []
    for l in lines:
        m = _HIT.fullmatch(l)
        files.append(m.group(1) if m else None)
    out, i = [], 0
    while i < len(lines):
        f, j = files[i], i
        if f is not None:
            while j + 1 < len(lines) and files[j + 1] == f:
                j += 1
        n = j - i + 1
        if f is not None and n >= 3 and n * (len(f) + 1) > len(f) + len(str(n)) + 3:
            out.append(f"§{n} {f}")
            out += [l[len(f) + 1 :] for l in lines[i : j + 1]]
            i = j + 1
        else:
            if lines[i].startswith(SIG):
                return None
            out.append(lines[i])
            i += 1
    return "\n".join(out)


def grep_decode(body: str) -> str:
    lines, out, i = body.split("\n"), [], 0
    while i < len(lines):
        if lines[i].startswith(SIG):
            n, _, f = lines[i][1:].partition(" ")
            n = int(n)
            out += [f + ":" + r for r in lines[i + 1 : i + 1 + n]]
            i += 1 + n
        else:
            out.append(lines[i])
            i += 1
    return "\n".join(out)


