# #19 Consecutive identical lines -> 'line [xN]'. Roundtrip. Trap: an original line that already ends in ' [xN]'.
# Escape: such a line is always written with an explicit ' [x1]' suffix, and decode reads only the LAST suffix.

_RLE = re.compile(r"(.*) \[x([0-9]+)\]")


def rle_encode(text: str) -> str:
    lines = text.split("\n")
    ambiguous = any(_RLE.fullmatch(l) for l in lines)
    out: list[str] = []
    for line, grp in itertools.groupby(lines):
        n = len(list(grp))
        if n >= 2 and len(line) + len(f" [x{n}]") < n * len(line) + n - 1:
            out.append(f"{line} [x{n}]")
        elif _RLE.fullmatch(line):
            out += [f"{line} [x1]"] * n
        else:
            out += [line] * n
    enc = "\n".join(out)
    return enc if (ambiguous or len(enc) < len(text)) else text


def rle_decode(text: str) -> str:
    out: list[str] = []
    for line in text.split("\n"):
        m = _RLE.fullmatch(line)  # greedy group 1: only the last ' [xN]' is the count
        out += [m.group(1)] * int(m.group(2)) if m else [line]
    return "\n".join(out)


