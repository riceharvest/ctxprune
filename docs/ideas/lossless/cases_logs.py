# #20 Non-consecutive exact duplicates: keep the first occurrence, annotate '[xN total]'. Equivalent, not roundtrip: where the
# later copies sat among the other lines is gone. Lines shorter than 12 characters are never folded (blank lines, '}').

_DUP = re.compile(r"(.*) \[x([0-9]+) total\]")
MIN_DUP = 12


def dedup_encode(text: str) -> str:
    lines = text.split("\n")
    counts = Counter(l for l in lines if len(l.strip()) >= MIN_DUP)
    ambiguous = any(_DUP.fullmatch(l) for l in lines)
    seen: set[str] = set()
    out: list[str] = []
    for l in lines:
        n = counts.get(l, 0)
        if n >= 2:
            if l in seen:
                continue
            seen.add(l)
            out.append(f"{l} [x{n} total]")
        else:
            out.append(f"{l} [x1 total]" if _DUP.fullmatch(l) else l)
    enc = "\n".join(out)
    return enc if (ambiguous or len(enc) < len(text)) else text


def _parse_dedup(e: str) -> list[tuple[str, int]]:
    parsed = []
    for l in e.split("\n"):
        m = _DUP.fullmatch(l)
        parsed.append((m.group(1), int(m.group(2))) if m else (l, 1))
    return parsed


def dedup_equivalent(x: str, e: str) -> bool:
    xl = x.split("\n")
    pe = _parse_dedup(e)
    el = [t for t, _ in pe]
    got: Counter = Counter()
    for t, n in pe:
        got[t] += n
    if got != Counter(xl):  # every distinct line keeps its exact total count
        return False
    it = iter(xl)
    if not all(any(t == o for o in it) for t in el):  # nothing moved, invented or edited: encoded is a subsequence of the original
        return False
    first = lambda ls: list(dict.fromkeys(ls))  # noqa: E731
    return first(xl) == first(el)  # the kept copy is the first one: order of first occurrences is unchanged


