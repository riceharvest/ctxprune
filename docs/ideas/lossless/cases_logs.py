# #24 Column-prefix factoring: consecutive lines that open with the same run of '[..] ' tokens share one header line.
# Roundtrip. Format: '§N <prefix>' then N lines holding only what follows the prefix. Counted, so rows need no escaping.

_PFX = re.compile(r"(?:\[[^\[\]]*\] )+")
COLS_MAGIC = "§cols (§N prefix: the next N lines start with prefix + space)\n"


def cols_core(text: str):
    lines = text.split("\n")
    pf = []
    for l in lines:
        m = _PFX.match(l)
        pf.append(m.group(0) if m else "")
    out, i = [], 0
    while i < len(lines):
        p, j = pf[i], i
        if p:
            while j + 1 < len(lines) and pf[j + 1] == p:
                j += 1
        n = j - i + 1
        if p and n >= 3 and n * len(p) > len(p) + len(str(n)) + 3:
            out.append(f"§{n} {p[:-1]}")
            out += [l[len(p):] for l in lines[i : j + 1]]
            i = j + 1
        else:
            if lines[i].startswith(SIG):
                return None  # an unblocked line starting with the sigil would read as a header
            out.append(lines[i])
            i += 1
    return "\n".join(out)


def cols_decode(body: str) -> str:
    lines, out, i = body.split("\n"), [], 0
    while i < len(lines):
        if lines[i].startswith(SIG):
            n, _, p = lines[i][1:].partition(" ")
            n = int(n)
            out += [p + " " + r for r in lines[i + 1 : i + 1 + n]]
            i += 1 + n
        else:
            out.append(lines[i])
            i += 1
    return "\n".join(out)


cols_encode, cols_unencode = framed(COLS_MAGIC, cols_core, cols_decode)


