def _ci_i__yscalar_in(tok: str):
    t = tok.strip()
    if t == "":
        return None
    if t[0] == '"':
        try:
            v = json.loads(t)
        except ValueError:
            raise _ci_i_YamlError("bad double-quoted scalar")
        if not isinstance(v, str):
            raise _ci_i_YamlError("bad double-quoted scalar")
        return v
    if t[0] == "'":
        if len(t) < 2 or t[-1] != "'":
            raise _ci_i_YamlError("bad single-quoted scalar")
        return t[1:-1].replace("''", "'")
    if t == "{}":
        return {}
    if t == "[]":
        return []
    if t[0] in "{[&*!|>%@`":
        raise _ci_i_YamlError("unsupported scalar " + t[:10])
    if t in ("true", "false"):
        return t == "true"
    if t in ("null", "~"):
        return None
    if re.fullmatch(r"-?\d+", t):
        return int(t)
    if re.fullmatch(r"-?\d+\.\d+", t):
        return float(t)
    return t

_ci_i__YKEY = re.compile(r"""^("(?:[^"\\]|\\.)*"|'[^']*'|[^\s:#"'\-\[\]{},&*!|>%@`][^:]*?|-[^\s:][^:]*?):(?:[ ](.*))?$""")

def _ci_i_yaml_lite(text: str):
    """Parse the YAML that kubectl and gcloud print. Raises _ci_i_YamlError on anything else (flow style, anchors, tabs)."""
    raw = text.replace("\r\n", "\n").split("\n")
    if any("\t" in l[: len(l) - len(l.lstrip(" \t"))] for l in raw):
        raise _ci_i_YamlError("tab indentation")
    n = len(raw)

    def sig(i):
        while i < n and (not raw[i].strip() or raw[i].lstrip().startswith("#")):
            i += 1
        return i if i < n else None

    def ind(i):
        return len(raw[i]) - len(raw[i].lstrip(" "))

    def is_dash(i):
        s = raw[i].lstrip(" ")
        return s.startswith("- ") or s == "-"

    def node(i):
        return seq(i, ind(i)) if is_dash(i) else mapping(i, ind(i))

    def seq(i, indent):
        out = []
        while True:
            j = sig(i)
            if j is None or ind(j) != indent or not is_dash(j):
                return out, (n if j is None else j)
            rest = raw[j].lstrip(" ")[1:]
            if rest.strip() == "":
                k = sig(j + 1)
                if k is None or ind(k) <= indent:
                    out.append(None)
                    i = j + 1
                    continue
                v, i = node(k)
                out.append(v)
                continue
            off = 1 + len(rest) - len(rest.lstrip(" "))
            raw[j] = " " * (indent + off) + rest.lstrip(" ")
            if _ci_i__YKEY.match(rest.strip()):
                v, i = mapping(j, indent + off)
            else:
                v, i = _ci_i__yscalar_in(rest), j + 1
            out.append(v)

    def mapping(i, indent):
        out = {}
        while True:
            j = sig(i)
            if j is None or ind(j) < indent:
                return out, (n if j is None else j)
            if ind(j) > indent:
                raise _ci_i_YamlError(f"unexpected indent at line {j + 1}")
            if is_dash(j):
                return out, j
            m = _ci_i__YKEY.match(raw[j].strip())
            if not m:
                raise _ci_i_YamlError(f"not a key at line {j + 1}")
            key = m.group(1)
            if key[0] in "\"'":
                key = _ci_i__yscalar_in(key)
            v = m.group(2)
            if v is None or v.strip() == "":
                k = sig(j + 1)
                if k is not None and (ind(k) > indent or (ind(k) == indent and is_dash(k))):
                    val, i = node(k)
                else:
                    val, i = None, j + 1
            elif v.strip()[0] in "|>" and re.fullmatch(r"[|>][+-]?", v.strip()):
                body, k = [], j + 1
                while k < n and (not raw[k].strip() or ind(k) > indent):
                    body.append(raw[k])
                    k += 1
                _ci_i_keep_nl = v.strip().endswith("+")
                while body and not body[-1].strip() and not _ci_i_keep_nl:
                    body.pop()
                first = next((b for b in body if b.strip()), "")
                w = len(first) - len(first.lstrip(" "))
                lines = [b[w:] if b.strip() else "" for b in body]
                val = "\n".join(lines) + ("" if v.strip().endswith("-") or not lines else "\n")
                if v.strip()[0] == ">":
                    val = val.replace("\n", " ")
                i = k
            else:
                val, i = _ci_i__yscalar_in(v), j + 1
            out[key] = val

    i = sig(0)
    if i is None:
        return None
    if ind(i) != 0 and not is_dash(i):
        raise _ci_i_YamlError("document does not start at column 0")
    val, end = node(i)
    if sig(end) is not None:
        raise _ci_i_YamlError(f"trailing content at line {end + 1}")
    return val

